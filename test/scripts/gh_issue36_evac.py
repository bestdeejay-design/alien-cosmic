# BODY не f-string (в тексте есть {yieldTotal} и пр.) — подставляем маркер заменой
BODY = BODY.replace('{MARKER}', MARKER)

def token():
    u = subprocess.run(['git', 'remote', 'get-url', 'origin'], capture_output=True, text=True).stdout.strip()
    m = re.match(r'https://(?:[^:]+:)?([^@]+)@github\.com/', u)
    if not m: sys.exit('нет токена в remote')
    return m.group(1)

TOK = token()

def req(method, path, body=None):
    r = urllib.request.Request(GH + path, method=method,
        headers={'Authorization': f'Bearer {TOK}', 'Accept': 'application/vnd.github+json'},
        data=json.dumps(body).encode() if body is not None else None)
    for attempt in range(3):
        try:
            with urllib.request.urlopen(r) as res:
                raw = res.read()
                return json.loads(raw) if raw else {}
        except urllib.error.HTTPError as e:
            if e.code == 404 and method == 'GET': return {}
            if e.code >= 500 and attempt < 2: time.sleep(2); continue
            raise
    return {}

# Идемпотентность: search API по маркеру + МГНОВЕННЫЙ листинг свежих issues
# (search-индекс отстаёт на минуты — урок #34 в обе стороны; дубль #37)
def marker_exists():
    hits = set()
    q = f'repo:{REPO} "{MARKER}" in:body type:issue'
    try:
        found = req('GET', '/search/issues?q=' + urllib.parse.quote(q) + '&per_page=5')
        hits |= {it['number'] for it in found.get('items', [])}
    except Exception:
        pass
    listed = req('GET', f'/repos/{REPO}/issues?state=all&sort=created&direction=desc&per_page=20')
    hits |= {it['number'] for it in (listed or []) if MARKER in (it.get('body') or '')}
    # канон = минимальный номер (первый созданный), остальные — дубли
    return min(hits) if hits else None

existing = marker_exists()
if existing:
    print(f'OK: issue #{existing} уже существует (маркер найден), дубль не создаю')
    sys.exit(0)

issue = req('POST', f'/repos/{REPO}/issues', {'title': TITLE, 'body': BODY})
num = issue['number']
print(f'OK: issue #{num} создан: {issue["title"][:60]}...')
